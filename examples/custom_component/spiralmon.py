"""The spiralmon: a transmon whose island is an oblique spiral, with a Quantcore junction to ground.

The island is a thin wire wound as a spiral (squashed to an ellipse and tilted, hence "oblique"), ending in a tail
and a landing pad. The Quantcore trilayer junction connects the pad to the ground plane across the clearance. A
curved readout claw follows the outer turn on the far side of the spiral and ends in a CPW tail: that is the pin
``claw``.

The shape is generated by :func:`spiral_shapes` (polygons in µm). The class :class:`Spiralmon` is a
:class:`freeform.FreeformComponent`: it gets the polygons, the pins and the junction line from that function.
:func:`drawn_spiralmon_file` writes the polygons to an ``.oas`` file, and :data:`DrawnSpiralmon` rebuilds the same
component from that file (``component_from_polygons``), as you would for a shape drawn by hand in KLayout.

Guide: docs/library/custom-components/spiralmon.md.
"""

from __future__ import annotations

import math
from pathlib import Path

from freeform import FreeformComponent, Pin, component_from_polygons, read_polygons, register
from kqcircuits.pya_resolver import pya
from kqcircuits.util.parameters import Param, pdt

HERE = Path(__file__).parent
LAYER_ISLAND, LAYER_CLAW = (10, 0), (11, 0)  # the layers of the drawn file


def _point(theta: float, p: dict) -> tuple[float, float]:
    """Centre line of the spiral at angle ``theta`` (rad): Archimedean, squashed, tilted (µm)."""
    r = p["r_in"] + p["pitch"] * theta / (2 * math.pi)
    x, y = r * math.cos(theta), p["squash"] * r * math.sin(theta)
    c, s = math.cos(math.radians(p["tilt"])), math.sin(math.radians(p["tilt"]))
    return x * c - y * s, x * s + y * c


def _normal(theta: float, p: dict) -> tuple[float, float]:
    """Unit normal of the centre line at ``theta``, pointing away from the spiral centre."""
    x0, y0 = _point(theta - 1e-3, p)
    x1, y1 = _point(theta + 1e-3, p)
    tx, ty = x1 - x0, y1 - y0
    n = math.hypot(tx, ty)
    return ty / n, -tx / n  # a counter-clockwise curve has its outside on the right


def _path(points, width, round_ends=False) -> pya.DPolygon:
    return pya.DPath([pya.DPoint(x, y) for x, y in points], width, 0, 0, round_ends).polygon()


def spiral_params(**overrides) -> dict:
    """The shape parameters with their defaults (µm, degrees)."""
    p = {
        "turns": 2.25,  # revolutions of the spiral
        "r_in": 30.0,  # start radius of the centre line
        "pitch": 44.0,  # radial advance per revolution (before the squash)
        "wire_w": 12.0,  # width of the spiral wire
        "squash": 0.6,  # minor / major axis of the ellipse
        "tilt": 35.0,  # rotation of the ellipse (the "oblique" angle)
        "tail_len": 40.0,  # straight tail after the last turn, ending in the landing pad
        "pad_w": 30.0,  # landing pad width (the junction window sits on it)
        "pad_h": 14.0,  # landing pad height
        "claw_w": 20.0,
        "claw_span": 70.0,  # claw length along the outer turn, degrees of the spiral angle
        "claw_gap": 10.0,  # gap between the outer turn and the claw
        "claw_tail": 80.0,  # claw tail length measured from the claw centre line
        "a": 10.0,  # CPW of the claw pin
        "b": 6.0,
        "clearance": 25.0,
    }
    unknown = set(overrides) - set(p)
    if unknown:
        raise ValueError(f"unknown spiral parameter(s) {sorted(unknown)}")
    return p | overrides


def spiral_shapes(**overrides) -> dict:
    """The drawn shape: ``{"island": [DPolygon], "claw": [DPolygon], "pins": [Pin], "junction": ((xa, ya), (xb, yb)),
    "geometry": {...}}``. The numbers in ``geometry`` (lengths, areas) feed the LOM model."""
    p = spiral_params(**overrides)
    t1 = 2 * math.pi * p["turns"]
    steps = max(int(120 * p["turns"]), 24)
    centre = [_point(t1 * i / steps, p) for i in range(steps + 1)]
    wire = _path(centre, p["wire_w"], round_ends=True)

    # tail after the last turn, straight outward, ending in the landing pad
    nx, ny = _normal(t1, p)
    ex, ey = centre[-1]
    tip = (ex + nx * p["tail_len"], ey + ny * p["tail_len"])
    tail = _path([(ex, ey), tip], p["wire_w"])
    angle = math.degrees(math.atan2(ny, nx))
    pad = pya.DPolygon(pya.DBox(-p["pad_h"], -p["pad_w"] / 2, 0, p["pad_w"] / 2))
    pad = pya.DCplxTrans(1, angle, False, tip[0], tip[1]) * pad
    junction = (tip, (tip[0] + nx * p["clearance"], tip[1] + ny * p["clearance"]))

    # readout claw: follows the outer turn on the far side of the end of the spiral, then a straight tail
    tc = t1 - math.pi
    half = math.radians(p["claw_span"]) / 2
    offset = p["wire_w"] / 2 + p["claw_gap"] + p["claw_w"] / 2
    arc = []
    for i in range(25):
        th = tc - half + 2 * half * i / 24
        nxx, nyy = _normal(th, p)
        x, y = _point(th, p)
        arc.append((x + nxx * offset, y + nyy * offset))
    claw = _path(arc, p["claw_w"])
    cx, cy = arc[12]
    cnx, cny = _normal(tc, p)
    port = (cx + cnx * p["claw_tail"], cy + cny * p["claw_tail"])
    claw_tail = _path([(cx, cy), port], p["a"])
    pin = Pin("claw", port[0], port[1], math.degrees(math.atan2(cny, cnx)), p["a"], p["b"], tail=p["claw_tail"] - 10)

    # numbers for the LOM model
    xs = [pt for poly in (wire, tail) for pt in [(q.x, q.y) for q in poly.each_point_hull()]]
    hull = _convex_hull(xs)
    wire_len = sum(math.dist(centre[i], centre[i + 1]) for i in range(len(centre) - 1))
    arc_len = sum(math.dist(arc[i], arc[i + 1]) for i in range(len(arc) - 1))
    geometry = {
        "hull_area_um2": _area(hull),
        "wire_length_um": wire_len + p["tail_len"],
        "claw_length_um": arc_len,
        "port": port,
        "tip": tip,
    }
    return {
        "island": [wire, tail, pad],
        "claw": [claw, claw_tail],
        "pins": [pin],
        "junction": junction,
        "geometry": geometry,
        "params": p,
    }


def _convex_hull(points):
    pts = sorted(set(points))
    if len(pts) < 3:
        return pts

    def cross(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])

    lower, upper = [], []
    for pt in pts:
        while len(lower) >= 2 and cross(lower[-2], lower[-1], pt) <= 0:
            lower.pop()
        lower.append(pt)
    for pt in reversed(pts):
        while len(upper) >= 2 and cross(upper[-2], upper[-1], pt) <= 0:
            upper.pop()
        upper.append(pt)
    return lower[:-1] + upper[:-1]


def _area(poly) -> float:
    return (
        abs(
            sum(
                poly[i][0] * poly[(i + 1) % len(poly)][1] - poly[(i + 1) % len(poly)][0] * poly[i][1]
                for i in range(len(poly))
            )
        )
        / 2
    )


class Spiralmon(FreeformComponent):
    """Spiral-island transmon: island = oblique spiral + tail + pad, junction from the pad to ground, one claw pin."""

    qcc_category = "qubit"

    turns = Param(pdt.TypeDouble, "Turns of the spiral", 2.25)
    r_in = Param(pdt.TypeDouble, "Start radius of the spiral", 30, unit="μm")
    pitch = Param(pdt.TypeDouble, "Radial advance per turn", 44, unit="μm")
    wire_w = Param(pdt.TypeDouble, "Spiral wire width", 12, unit="μm")
    squash = Param(pdt.TypeDouble, "Minor / major axis of the spiral ellipse", 0.6)
    tilt = Param(pdt.TypeDouble, "Tilt of the ellipse (oblique angle)", 35, unit="deg")
    claw_w = Param(pdt.TypeDouble, "Claw width", 20, unit="μm")
    claw_span = Param(pdt.TypeDouble, "Claw length along the outer turn", 70, unit="deg")
    claw_gap = Param(pdt.TypeDouble, "Gap between the outer turn and the claw", 10, unit="μm")

    _SHAPE_KEYS = ("turns", "r_in", "pitch", "wire_w", "squash", "tilt", "claw_w", "claw_span", "claw_gap", "clearance")

    def _shapes(self) -> dict:
        return spiral_shapes(a=self.a, b=self.b, **{k: float(getattr(self, k)) for k in self._SHAPE_KEYS})

    def polygons(self):
        s = self._shapes()
        return s["island"] + s["claw"]

    def pins(self):
        return self._shapes()["pins"]

    def junction_line(self):
        return self._shapes()["junction"]

    @classmethod
    def qcc_lom(cls, name: str, inst, pdk):
        """Grounded transmon: island (C to ground, junction to ground), the claw as its own node (C_g to the island,
        C to ground). Rough formulas on the shape (see ``estimates.py``) until a Q3D C-matrix replaces them; FEM nets
        ``<name>.island`` and ``<name>.claw``."""
        from quantcore_circuits.lom import estimates as est
        from quantcore_circuits.lom.fragment import (
            Element as LomElement,
        )
        from quantcore_circuits.lom.fragment import (
            Fragment,
            cell_params,
            junction_element,
            junction_kind,
        )

        p = cell_params(inst)
        eps = est.substrate_eps(pdk)
        shape = spiral_shapes(
            a=float(p.get("a", 10)),
            b=float(p.get("b", 6)),
            **{k: float(p[k]) for k in cls._SHAPE_KEYS if k in p},
        )
        g, sp = shape["geometry"], shape["params"]
        r_eq = math.sqrt(g["hull_area_um2"] / math.pi)
        # the spiral's turns are one conductor: its outline is a filled ellipse to the ground plane. An equivalent
        # disk in a clearance of sp["clearance"] is the estimate; the gaps between the turns lower it a little.
        c_island = est.disk_to_ground(r_eq, sp["clearance"], eps)
        c_g = est.coplanar_coupling(g["claw_length_um"], sp["claw_w"], sp["wire_w"], sp["claw_gap"], eps)
        c_claw = est.cpw_line(g["claw_length_um"] + sp["claw_tail"], sp["claw_w"], sp["clearance"], eps)
        formula = f"equivalent disk r = {r_eq:.0f} µm of the spiral outline, clearance {sp['clearance']:g} µm"
        frag = Fragment(
            nodes={"island": {"island": f"{name}.island"}, "claw": {"island": f"{name}.claw"}},
            port_nodes={"claw": "claw", "squid_a": "island", "squid_b": "gnd"},
        )
        els = frag.elements
        els.append(LomElement(f"C_{name}", "C", ("island", "gnd"), est.cap(c_island, "rough", formula)))
        els.append(
            LomElement(
                f"Cg_{name}_claw", "C", ("island", "claw"), est.cap(c_g, "rough", "curved claw along the outer turn")
            )
        )
        els.append(
            LomElement(f"Cc_{name}_claw", "C", ("claw", "gnd"), est.cap(c_claw, "rough", "claw + tail as a CPW stub"))
        )
        kind = "SQUID" if junction_kind(str(p.get("junction_type"))) == "SQUID" else "JJ"
        els.append(junction_element(name, "island", "gnd", inst, kind, drawn_params=p))
        lj = els[-1].value.get("Lj_nH")
        if lj:
            frag.knobs[f"{name}.junction.Lj_nH"] = (round(lj * 0.5, 3), round(lj * 1.5, 3))
        frag.knobs[f"{name}.turns"] = (round(float(p["turns"]) * 0.6, 2), round(float(p["turns"]) * 1.6, 2))
        frag.notes.append(
            f"{name}: the spiral's own inductance (about 1 nH per mm of wire, "
            f"{g['wire_length_um'] / 1000:.1f} mm here) "
            "is not in the model; capacitances are rough, run a C-matrix to replace them"
        )
        return frag


# ---- the same shape from a drawn file ------------------------------------------------------
def drawn_spiralmon_file(path=None, **overrides) -> Path:
    """Write the spiral polygons to an ``.oas`` file (layer 10/0 island, 11/0 claw): a stand-in for a shape drawn
    in KLayout. Returns the path (default ``examples/custom_component/spiralmon_drawn.oas``)."""
    from freeform import polygons_to_oas

    s = spiral_shapes(**overrides)
    return polygons_to_oas({LAYER_ISLAND: s["island"], LAYER_CLAW: s["claw"]}, path or HERE / "spiralmon_drawn.oas")


def drawn_spiralmon(path=None, name: str = "DrawnSpiralmon"):
    """A component class for the drawn file: its polygons, the pin and the junction line of the default shape. In
    your own drawing you would measure the pin and the junction position in KLayout (ruler, or the cursor
    coordinates) and type them here. The file is written first when it does not exist (``*.oas`` files are
    git-ignored in this repository, so the example regenerates its stand-in drawing)."""
    path = Path(path or HERE / "spiralmon_drawn.oas")
    if not path.exists():
        drawn_spiralmon_file(path)
    s = spiral_shapes()
    polys = read_polygons(path, LAYER_ISLAND) + read_polygons(path, LAYER_CLAW)
    return component_from_polygons(name, polys, s["pins"], s["junction"], module="spiralmon")


# a fixed-shape component class from the file: the dotted path "spiralmon.DrawnSpiralmon"
DrawnSpiralmon = drawn_spiralmon()

register(Spiralmon)
