"""Regenerate the generated pages of the docs site (docs/hosting.md ▸ Regenerate the generated pages).

Run from the repo root with the ``qcd`` env active::

    python scripts/make_docs.py              # docs/components/cells/ pages + docs/reference/cli.md
    python scripts/make_docs.py --render     # also draw pin pictures for components that have none
    python scripts/make_docs.py --render --all   # redraw every pin picture

The options are passed on to ``scripts/make_component_docs.py``. Then build the site with ``sphinx-build -b html docs
docs/_build/html`` (any env with ``docs/requirements.txt``).
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CLI_MD = ROOT / "docs" / "reference" / "cli.md"
CLI_HEAD = "% generated by scripts/make_docs.py (typer utils docs) -- do not edit.\n\n"


def main(argv: list[str]) -> int:
    env = {**os.environ, "PYTHONUTF8": "1", "PYTHONIOENCODING": "utf-8", "QCC_LIVE": "0"}
    rc = subprocess.run([sys.executable, str(ROOT / "scripts" / "make_component_docs.py"), *argv], env=env,
                        cwd=ROOT, check=False).returncode
    if rc:
        return rc
    CLI_MD.parent.mkdir(parents=True, exist_ok=True)
    rc = subprocess.run([sys.executable, "-m", "typer", "quantcore_circuits.cli", "utils", "docs", "--name", "qcc",
                         "--title", "qcc command line", "--output", str(CLI_MD)], env=env, cwd=ROOT,
                        check=False).returncode
    if rc:
        return rc
    text = CLI_MD.read_text(encoding="utf-8")
    if not text.startswith(CLI_HEAD):
        CLI_MD.write_text(CLI_HEAD + text, encoding="utf-8")
    print(f"{CLI_MD.relative_to(ROOT)} written")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
