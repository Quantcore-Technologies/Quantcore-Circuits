"""Generate the component reference pages ``docs/components/cells/<Cell>.md`` (+ ``index.md``) from the live library.

Run from the repo root (env ``qcd``, ``QCC_LIVE=0``)::

    python scripts/make_component_docs.py                  # rewrite every page (deterministic)
    python scripts/make_component_docs.py --render         # first render the pin images that are missing
    python scripts/make_component_docs.py --render --all   # re-render every pin image
    python scripts/make_component_docs.py --only Xmon BondPad --render   # restrict to some cells

Scope: every catalog cell (Quantcore, KQC, Metal) that is not a chip or a wafer. Everything comes from the library:
the catalog (``layouts.catalog``), the registry (``layouts.registry``: schema, ports of a default instance), the LOM
registry (``lom.fragment``). Nothing is read from ``build/``. Hand-written notes in ``docs/components/notes/<Cell>.md``
are included into the cell's page with a MyST ``{include}`` directive, so they survive regeneration.

Page / image name of a cell = its ref with ``:`` replaced by ``_``
(``metal:TransmonPocket`` -> ``metal_TransmonPocket``).
"""

