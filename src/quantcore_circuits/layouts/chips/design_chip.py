"""``DesignChip``: a KQC ``Chip`` that executes a resolved build plan.

All decisions (snap transforms, routes, fixed lengths, parameter inheritance) are made beforehand by
:func:`quantcore_circuits.assembly.plan.plan_design`, outside the PCell. KLayout swallows exceptions raised inside
PCell code, so this
class only replays the plan; KQC's ``Chip.post_build`` then adds frame, ground grid and layer merging as usual.
"""

import json

from kqcircuits.chips.chip import Chip
from kqcircuits.elements.waveguide_composite import WaveguideComposite
from kqcircuits.pya_resolver import pya
from kqcircuits.util.node import Node
from kqcircuits.util.parameters import Param, pdt

from quantcore_circuits.route.waveguide import has_corner_radii

# KQC draws each instance name with KLayout's Basic TEXT cell at magnification 400; its capital letters are 0.7 of the
# magnification tall (280 µm). ``DesignChip.instance_label_height`` sets that height.
LABEL_CAP_RATIO = 0.7
KQC_LABEL_HEIGHT = 400.0 * LABEL_CAP_RATIO


def _instance_name_labels(cell, mag: float) -> None:
    """KQC's ``chip_helpers.produce_instance_name_labels`` with another magnification (same layer, placement and
    upright / unmirrored rule, ``label_trans`` applied)."""
    from kqcircuits.defaults import default_layers  # pylint: disable=import-outside-toplevel
    from kqcircuits.elements.element import insert_cell_into  # pylint: disable=import-outside-toplevel

    layout = cell.layout()
    for inst in cell.each_inst():
        inst_id = inst.property("id")
        if not inst_id:
            continue
        label_cell = layout.create_cell("TEXT", "Basic", {"layer": default_layers["instance_names"], "text": inst_id,
                                                           "mag": float(mag)})
        label_trans = inst.dcplx_trans
        if 90 < label_trans.angle < 270:
            label_trans.angle += 180
        label_trans.mirror = False
        rel = inst.property("label_trans")
        if rel is not None:
            label_trans = label_trans * pya.DCplxTrans.from_s(rel)
        insert_cell_into(cell, label_cell, label_trans)


class DesignChip(Chip):
    """Chip generated from a ``design.json`` build plan."""

    qcc_category = "chip"

    plan = Param(pdt.TypeString, "build plan (JSON, generated by quantcore_circuits.assembly)", "{}", hidden=True)
    name_brand = Param(pdt.TypeString, "Name of the brand", "QCT")  # Quantcore (2026-11-03); KQC: its own
    die_frame = Param(pdt.TypeBoolean, "Quantcore die frame (PDK dicing/alignment markers, device ID)", True)
    cheese = Param(
        pdt.TypeString,
        "Ground cheese: auto (PDK band unless the design has its own), pdk (band always), chip (PDK squares over "
        "the whole die), original (none added)",
        "auto",
        choices=["auto", "pdk", "chip", "original"],
    )
    device_id_side = Param(
        pdt.TypeString,
        "Device ID side: auto (bottom, else the first empty of top/left/right), bottom, top, left or right",
        "auto",
        choices=["auto", "bottom", "top", "left", "right"],
    )
    instance_label_height = Param(
        pdt.TypeDouble,
        "Height of the instance name labels (capital letters, µm; 0 = no labels; KQC: 280)",
        KQC_LABEL_HEIGHT,
        unit="µm",
    )

    def _produce_instance_name_labels(self):
        """KQC's instance name labels (layer ``instance_names``, an annotation layer: not in the fab mask or the
        simulations) at ``instance_label_height``. The default is KQC's own call, so a default build is unchanged."""
        height = float(self.instance_label_height)
        if abs(height - KQC_LABEL_HEIGHT) < 1e-9:
            super()._produce_instance_name_labels()
        elif height > 0:
            _instance_name_labels(self.cell, height / LABEL_CAP_RATIO)

    def build(self):
        from quantcore_circuits.layouts.registry import resolve_cell, shape_params  # pylint: disable=C0415

        plan = json.loads(self.plan)
        launchers = plan.get("launchers")
        edge = plan.get("pad_edge")  # PDK pad rule: launchers' outer edge this far from the die edge
        if isinstance(launchers, dict):  # named launchers: {"type", "assign": {pad number: name}, "enabled", ...}
            self._produce_launcher_spec(launchers, edge)
        elif launchers and edge is not None:
            self._produce_launcher_spec({"type": launchers}, edge)
        elif launchers:
            self.produce_launchers(launchers)

        pads = []  # pad / launcher footprints: device-ID anchors
        placed = {}  # instance name → placed instance (route joins)
        for name, inst in plan.get("instances", {}).items():
            trans = pya.DCplxTrans.from_s(inst["trans"])
            if inst["cell"].startswith("static:"):
                cell = _static_cell(self.layout, inst["cell"][len("static:") :], name)
            else:
                cls = resolve_cell(inst["cell"])
                cell = cls.create(self.layout, library=self.LIBRARY_NAME, **shape_params(cls, inst["params"]))
                if _is_pad(cls):
                    pads.append(cell.dbbox().transformed(trans))
            placed[name], _ = self.insert_cell(cell, trans, inst_name=name, rec_levels=0)
            for port in inst.get("static_ports", []):
                pos = trans * pya.DPoint(*port["at"])
                self.refpoints[f"{name}_port_{port['name']}"] = pos

        for name, route in plan.get("routes", {}).items():
            nodes = Node.nodes_from_string(route["nodes"])
            cls = WaveguideComposite
            if has_corner_radii(nodes):  # per-corner bend radii (Waypoint.r)
                from quantcore_circuits.route.waveguide import waveguide_class  # pylint: disable=C0415

                cls = waveguide_class(nodes)
            # the cell is drawn around its first node and placed there: KQC puts a "base" refpoint at the cell origin,
            # so a cell drawn in chip coordinates has a bounding box from the die origin to the route (what KLayout's
            # selection shows). The offset is a whole µm, so the flattened geometry is the same.
            origin = pya.DVector(round(nodes[0].position.x), round(nodes[0].position.y))
            for node in nodes:
                node.position = node.position - origin
            cell = cls.create(self.layout, library=self.LIBRARY_NAME, nodes=nodes, **route["params"])
            joined = self._join_ends(cell, nodes, route, origin, placed) if route.get("joins") else None
            if joined is not None:  # an end met a cell's etch across a hairline: drawn a little into the cell
                cell = cls.create(self.layout, library=self.LIBRARY_NAME, nodes=joined[0], **route["params"])
            self.insert_cell(cell, pya.DTrans(origin), inst_name=name)
            for end, shift in (joined[1] if joined else {}).items():  # the route's ports stay at the cell's ports
                for key in (f"{name}_port_{end}", f"{name}_port_{end}_corner"):
                    if key in self.refpoints:
                        self.refpoints[key] = self.refpoints[key] - shift
                if f"{name}_port_{end}" in self.refpoints:
                    self._bridge_port_texts(self.refpoints[f"{name}_port_{end}"], shift, route["params"])

        if plan.get("metal"):  # extra ground (hanger couplers with narrowed facing gaps), before the cheese sees it
            dbu = self.layout.dbu
            layer = self.get_layer("base_metal_addition")
            for pts in plan["metal"]:
                self.cell.shapes(layer).insert(pya.DPolygon([pya.DPoint(*q) for q in pts]).to_itype(dbu))

        if plan.get("frame"):
            from quantcore_circuits.layouts.chips.frame import draw_frame  # pylint: disable=import-outside-toplevel
            from quantcore_circuits.pdk import DieFrame  # pylint: disable=import-outside-toplevel

            frame = DieFrame(**{k: tuple(v) if isinstance(v, list) else v for k, v in plan["frame"].items()})
            text_layer = self.get_layer("base_metal_gap_wo_grid")
            occupied = _footprints(self.cell, text_layer)
            pads += _launcher_boxes(self.cell)
            slot = draw_frame(
                self.cell, self.box, frame, plan.get("device_id", ""), text_layer, self.device_id_side, occupied, pads
            )
            self._qcc_frame, self._qcc_device_id = frame, (slot if slot is not None else False)
            if slot is not None:
                self.refpoints["qcc_device_id_p1"], self.refpoints["qcc_device_id_p2"] = slot.p1, slot.p2
            else:  # optional: no room (or no name) → no ID and no keep-out
                self.refpoints["qcc_device_id_none"] = self.box.p1

        if plan.get("cheese"):
            self._produce_pdk_cheese(plan["cheese"])

    def _join_ends(self, cell, nodes, route: dict, origin, placed: dict):
        """:func:`~quantcore_circuits.route.waveguide.joined_nodes` for one route of the plan (its ``joins``)."""
        from kqcircuits.defaults import default_faces  # pylint: disable=import-outside-toplevel

        from quantcore_circuits.route.waveguide import joined_nodes  # pylint: disable=import-outside-toplevel

        params = route["params"]
        face = (params.get("face_ids") or self.face_ids)[0]
        layer = self.layout.layer(default_faces[face]["base_metal_gap_wo_grid"])
        half = float(params.get("a", self.a)) / 2 + float(params.get("b", self.b))
        return joined_nodes(cell, nodes, route["nodes"], origin, route["joins"], placed, layer, half)

    def _bridge_port_texts(self, at, shift, params: dict) -> None:
        """A joined route end's port text sits ``shift`` (:data:`~quantcore_circuits.route.waveguide.JOIN_SHIFT`)
        inside the cell, away from the cell's port text at ``at``: a 2 dbu wide strip on the ports layer (an annotation
        layer, not in the fab mask or the simulation) joins the two, so the netlist extraction (port texts enlarged by
        1 dbu) still sees the connection."""
        from kqcircuits.defaults import default_layers  # pylint: disable=import-outside-toplevel

        face = (params.get("face_ids") or self.face_ids)[0]
        dbu = self.layout.dbu
        path = pya.DPath([at, at + shift], 2 * dbu, dbu, dbu)
        self.cell.shapes(self.layout.layer(default_layers[f"{face}_ports"])).insert(path.polygon())

    def _produce_pdk_cheese(self, spec: dict) -> None:
        """PDK cheese (``pdk.CheeseRule``: a band around the 3/0 keep-outs, or the whole die for ``fill="chip"``),
        drawn into ``ground_grid`` (KQC's cheese layer, part of the 1/0 etch): inside the design area, clear of the
        frame markers and the device ID, and clear of TSVs, indium bumps, UBM and airbridges
        (:func:`~quantcore_circuits.layouts.wafers.fab_export.cheese_avoid_region`; KQC's automatic ground TSVs and
        bumps come later, in :meth:`post_build`)."""
        from quantcore_circuits.layouts.chips.frame import design_area, keepouts  # pylint: disable=C0415
        from quantcore_circuits.layouts.wafers.fab_export import (  # pylint: disable=import-outside-toplevel
            cheese_avoid_region,
            cheese_holes,
            etch_region,
            ground_region,
            keepout_region,
        )
        from quantcore_circuits.pdk import CheeseRule, get_pdk  # pylint: disable=import-outside-toplevel

        pdk = get_pdk(spec["pdk"])
        rule = CheeseRule(**spec["rule"])
        dbu = self.layout.dbu
        frame = getattr(self, "_qcc_frame", None)
        allowed = pya.Region((design_area(self.box, frame) if frame is not None else self.box).to_itype(dbu))
        if spec.get("edge"):  # the original rule keeps its holes this far from the die edge
            allowed &= pya.Region(self.box.enlarged(-float(spec["edge"]), -float(spec["edge"])).to_itype(dbu))
        exclude = pya.Region()
        if frame is not None:
            for box in keepouts(self.box, frame, getattr(self, "_qcc_device_id", None)).values():
                exclude.insert(box.to_itype(dbu))
        etch = etch_region(self.cell, pdk.face, grid=False)
        keep = keepout_region(self.cell, pdk, etch)
        avoid = cheese_avoid_region(self.cell, pdk)  # TSVs, bumps, UBM, airbridges: no hole on or next to them
        ground = ground_region(self.cell, pdk, self.box, rule, etch)  # the ground plane: no holes in pads, islands
        holes = cheese_holes(keep, rule, dbu, allowed, exclude, avoid, ground)
        self.cell.shapes(self.get_layer("ground_grid")).insert(holes)
        self._qcc_cheese = (pdk, rule)

    def post_build(self):
        """KQC's ``post_build`` (frames, ground TSVs and bumps, labels); then the PDK cheese drawn in :meth:`build` loses
        the holes that now lie on or next to KQC's automatic ground TSVs and bumps (``with_gnd_tsvs``,
        ``with_gnd_bumps``), which KQC places after the build."""
        super().post_build()
        cheese = getattr(self, "_qcc_cheese", None)
        if cheese is None or not (self.with_gnd_tsvs or self.with_gnd_bumps):
            return
        from quantcore_circuits.layouts.wafers.fab_export import cheese_avoid_region  # pylint: disable=C0415

        pdk, rule = cheese
        avoid = cheese_avoid_region(self.cell, pdk)
        if avoid.is_empty():
            return
        shapes = self.cell.shapes(self.get_layer("ground_grid"))
        holes = pya.Region(shapes)
        d = round(rule.clearance / self.layout.dbu) + 1
        near = holes.interacting(avoid.minkowski_sum(pya.Box(-d, -d, d, d)))
        if not near.is_empty():
            shapes.clear()
            shapes.insert(holes - near)

    def _produce_launcher_spec(self, spec: dict, edge: float | None = None) -> None:
        """Launchers from a ``design.json`` :class:`~quantcore_circuits.design.schema.Launchers` dict: a KQC preset, a
        preset with overrides, or a custom set (KQC ``produce_n_launchers``; the chip keeps its own box).

        ``edge`` (the PDK pad rule, ``DieFrame.pad_edge``) sets ``launcher_indent`` so each launcher's outer etch edge
        is ``edge`` µm from the die edge, unless the spec gives its own ``indent``."""
        from kqcircuits.defaults import default_sampleholders  # pylint: disable=import-outside-toplevel

        assign = {int(k): v for k, v in (spec.get("assign") or {}).items()} or None
        names = {
            "n": "n",
            "launcher_type": "launcher_type",
            "width": "launcher_width",
            "gap": "launcher_gap",
            "indent": "launcher_indent",
            "pitch": "pad_pitch",
            "frame_gap": "launcher_frame_gap",
        }
        overrides = {names[k]: v for k, v in spec.items() if k in names and v is not None}
        kind = spec.get("type", "custom")
        if not overrides and edge is None:
            self.produce_launchers(kind, assign, spec.get("enabled"))
            return
        kw = dict(default_sampleholders.get(kind, {}))
        if overrides:
            kw.pop("chip_box", None)  # overridden / custom launchers keep the chip's own box
        if kind == "SMA8" and not assign and "n" not in overrides:  # KQC produce_launchers' default SMA8 names
            assign = {1: "NW", 2: "NE", 3: "EN", 4: "ES", 5: "SE", 6: "SW", 7: "WS", 8: "WN"}
        if not kw and not overrides:
            return  # not a KQC sample holder (KQC produce_launchers draws nothing either)
        kw.update(overrides)
        if edge is not None and "launcher_indent" not in overrides and "launcher_width" in kw:
            kw["launcher_indent"] = launcher_indent(kw, edge)
        if isinstance(kw.get("n"), list):
            kw["n"] = tuple(kw["n"])  # pads per side: KQC expects a tuple
        kw.setdefault("launcher_type", "RF")
        self.produce_n_launchers(**kw, launcher_assignments=assign, enabled=spec.get("enabled"))

    def produce_ground_grid(self):
        """KQC grids only faces with a KQC ChipFrame; with the PDK die frame, grid the design area instead, clear of
        the marker areas and the device ID."""
        frame = getattr(self, "_qcc_frame", None)
        if frame is None:
            super().produce_ground_grid()
            return
        from quantcore_circuits.layouts.chips.frame import design_area, keepouts  # pylint: disable=C0415

        avoid = self.cell.shapes(self.get_layer("ground_grid_avoidance"))
        for box in keepouts(self.box, frame, getattr(self, "_qcc_device_id", None)).values():
            avoid.insert(box)
        self.produce_ground_on_face_grid(design_area(self.box, frame), 0)


def launcher_indent(kw: dict, edge: float) -> float:
    """KQC ``launcher_indent`` (die edge → launcher port) that puts a launcher's outer etch edge ``edge`` µm from the
    die edge: RF ``Launcher`` = taper (width) + pad (width) + frame gap; ``LauncherDC`` = half its 100 µm-wider gap
    square."""
    width = float(kw["launcher_width"])
    if kw.get("launcher_type", "RF") == "DC":
        return edge + (width + 100.0) / 2
    frame_gap = kw.get("launcher_frame_gap")
    frame_gap = float(kw.get("launcher_gap", 0.0) if frame_gap is None else frame_gap)
    return edge + 2 * width + frame_gap


def _is_pad(cls) -> bool:
    """Pads and launchers (the cells the device ID may sit beside)."""
    category = getattr(cls, "qcc_category", "")
    return category in ("launcher", "termination") or "Launch" in cls.__name__ or cls.__name__.endswith("Pad")


def _launcher_boxes(cell) -> list:
    """Footprints of chip-frame launchers (KQC ``produce_launchers``: Launcher cells inserted into the chip)."""
    layout = cell.layout()
    out = []
    for inst in cell.each_inst():
        child = layout.cell(inst.cell_index)
        if child.name.split("$", 1)[0] in ("Launcher", "Launcher DC", "LauncherDC"):
            out.append(child.dbbox().transformed(inst.dcplx_trans))
    return out


def _footprints(cell, gap_layer: int):
    """What the device ID must avoid: each component's footprint (its etch bounding box, as the DRC uses: a pad's
    interior is metal, not free space) and the etched polygons of routes (an L-shaped route's box is mostly empty)."""
    occupied = pya.Region()
    layout = cell.layout()
    for inst in cell.each_inst():
        child = layout.cell(inst.cell_index)
        if child.name.startswith("Waveguide Composite"):
            occupied.insert(pya.Region(child.begin_shapes_rec(gap_layer)).transformed(inst.cplx_trans))
            continue
        box = child.bbox_per_layer(gap_layer)
        if box.empty():
            box = child.bbox()
        if not box.empty():
            occupied.insert(box.transformed(inst.cplx_trans))
    for shape in cell.shapes(gap_layer).each():  # anything drawn directly into the chip cell
        occupied.insert(shape.polygon if shape.polygon is not None else shape.bbox())
    return occupied


def ensure_registered():
    """Make sure DesignChip (and all Quantcore cells) are registered in the KQC libraries."""
    from quantcore_circuits import layouts  # pylint: disable=import-outside-toplevel

    layouts.ensure_loaded()


def _static_cell(layout, path, name):
    """Copy the top cell of a static OAS/GDS file into ``layout``."""
    src = pya.Layout()
    src.read(path)
    top = src.top_cell()
    cell = layout.create_cell(f"static_{name}")
    cell.copy_tree(top)
    return cell
